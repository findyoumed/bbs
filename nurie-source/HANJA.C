void     hgHanjaInit(char *fname, int qsize)
{
	if (qsize > 500) qsize = 500;
	hanja = hgOpenExtFont(fname, 2, 16, qsize);

	if (hanja != NULL) {
		hanjaokflag = hgTRUE;
		hjps = &hanja_real_out;
	}
}

void     hgHanjaEnd()
{
	if (hanjaokflag) hgCloseExtFont(hanja);
}

int      ishanja(char *str, int pos)
{
	byte   high, low;

	high = (byte)str[pos];
	low = (byte)str[pos + 1];

	if ((high >= 0xe0 && high <= 0xf9) && ((low >= 0x31 && low <= 0x7e)
					|| (low >= 0x91 && low <= 0xfe)))
		return(hgSUCCESS);
	else return(hgFAIL);
}

void     hgHanjaToHangul(int *ch)
{
	byte   high, low;
	int    i;
	unsigned  off;

	high = (byte)(*ch >> 8);
	low = (byte)*ch;

	if ((high >= 0xe0 && high <= 0xf9) && ((low >= 0x31 && low <= 0x7e)
					|| (low >= 0x91 && low <= 0xfe))) {
		if (low >= 0x91) low -= 18;
		low -= 0x31;
		off = ((high - 0xe0) * 188 + low);
	}
	else return;

	for (i = 0;i < 473;i++)
		if (hanjatable[i][2] > off) break;
	i--;

	high = hanjatable[i][0] / 256;
	low = hanjatable[i][0] % 256;
	*ch = (high << 8) + low;
}

void     hgHanjaToHangulStr(char *str)
{
	int   i, ch;

	for (i = 0;i < strlen(str);) {
		if (ishanja(str, i)) {
			ch = (str[i] << 8) + (byte)str[i + 1];

			hgHanjaIn(&ch);

			str[i] = (ch >> 8);
			str[i + 1] = ch;
			i += 2;
		}
		else i++;
	}
}

void     hgHanjaIn(int *ch)
{
	HDIRBOX *p;
	WIDTH    w = { 280, 178 };

	char   *items[_MAXDIR];
	byte   ret[5];
	byte   high, low;
	int    i;
	int    x, y;
	int    findflag = hgFALSE;
	int    retflag;
	unsigned  hanjacode;

	x = (hgGetx2r() + hgGetx1r()) / 2 - w.xwidth / 2;
	y = (hgGety2r() + hgGety1r()) / 2 - w.ywidth / 2;

	for (i = 0;i < 473;i++)
		if (hanjatable[i][0] == *ch) {
			findflag = hgTRUE;
			break;
		}

	if (!findflag) {
		hgHanjaToHangul(ch);
		return;
	}

	for (retflag = 0;retflag < hanjatable[i][1];retflag++) {
		hanjacode = hanjatable[i][2] + retflag;
		high = (hanjacode / 188) + 0xe0;
		low = hanjacode % 188;
		if (low < 78) low += 0x31;
		else low += 0x91 - 78;

		items[retflag] = (char *)malloc((size_t)3);
		items[retflag][0] = high;
		items[retflag][1] = low;
		items[retflag][2] = 0;
	}
	items[retflag] = (char *)malloc((size_t)3);
	items[retflag][0] = 0;
	items[retflag][1] = 0;
	items[retflag][1] = 0;

	hgSetSaveOn();
	p = hgHDIRBOX_Load(items, w, 8, 6);
	hgHDIRBOX_Choose(p, x, y, "Ðe¸a ·³b", ret);
	hgHDIRBOX_Free(&p);
	hgSetSaveOff();
	hgRestore();

	for (retflag = 0;retflag <= hanjatable[i][1];retflag++)
		free(items[retflag]);

	if (strcmp(ret, "")) *ch = (ret[0] << 8) + ret[1];
}

void     hanja_real_out(char *str, int pos)
{
	char   sattr;
	byte   high, low;
	int    i;
	int    fac = 1;
	unsigned  off;

	high = str[pos];
	low = str[pos + 1];

	if ((high >= 0xe0 && high <= 0xf9) && ((low >= 0x31 && low <= 0x7e)
					|| (low >= 0x91 && low <= 0xfe))) {
		if (low >= 0x91) low -= 18;
		low -= 0x31;
		off = ((high - 0xe0) * 188 + low);
	}

	sattr = hgGetExtAttr();
	hgSetExtAttr(hgGetHAttr());
	hgPutExtFont(hanja, _xpos, _ypos, off);
	hgSetExtAttr(sattr);

	for (i = 1;i < hgGetXFactor();i++) fac *= 2;
	_xpos += (16 * fac);
}
