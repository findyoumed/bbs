export function findDoorArt(input) {
  const value = String(input || '').trim().toLowerCase();
  if (!value) return null;
  const byIndex = /^\d+$/.test(value) ? DOOR_ART[Number(value) - 1] : null;
  return byIndex || DOOR_ART.find((item) => item.key === value) || null;
}
